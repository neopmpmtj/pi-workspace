#!/usr/bin/env bash
set -euo pipefail

# export-partner-agent.sh — generate a self-contained installer for a partner agent.
#
# Usage:   export-partner-agent.sh <name> [source-path]
# Output:  ~/.pi/agent/partner-agents/exports/<name>/install-<name>.sh
#
# The generated installer rebuilds the agent on any target Pi as a partner agent at
# ~/.pi/partner-agents/<name>/, linking the target's own credentials, reinstalling its
# packages, registering it, adding a pi-<name> alias, and running a smoke test.

NAME="${1:?usage: export-partner-agent.sh <name> [source-path]}"

# ---- resolve source workspace ---------------------------------------------------
if [ -n "${2:-}" ]; then
  SRC="$(cd "$2" 2>/dev/null && pwd || true)"
  [ -n "$SRC" ] || { echo "ERROR: source path '$2' not found" >&2; exit 1; }
elif [ -d "$HOME/.pi/partner-agents/$NAME" ]; then
  SRC="$HOME/.pi/partner-agents/$NAME"
elif [ -d "$HOME/.pi/$NAME" ]; then
  SRC="$HOME/.pi/$NAME"
else
  echo "ERROR: cannot locate agent '$NAME' (tried ~/.pi/partner-agents/$NAME and ~/.pi/$NAME)" >&2
  exit 1
fi
SRC="$(cd "$SRC" && pwd)"
echo "Exporting agent '$NAME' from $SRC"

[ -f "$SRC/settings.json" ] || { echo "ERROR: $SRC/settings.json not found" >&2; exit 1; }
command -v jq >/dev/null 2>&1 || { echo "ERROR: 'jq' is required by the exporter (not the installer)" >&2; exit 1; }

# ---- extract settings (these become the installer's canonical settings.json) ----
DEF_PROVIDER="$(jq -r '.defaultProvider // empty' "$SRC/settings.json")"
DEF_MODEL="$(jq -r '.defaultModel // empty' "$SRC/settings.json")"
THINKING="$(jq -r '.defaultThinkingLevel // empty' "$SRC/settings.json")"
THEME="$(jq -r '.theme // empty' "$SRC/settings.json")"
PKGS_JSON="$(jq -c '.packages // []' "$SRC/settings.json")"
PKGS_LIST="$(jq -r '.packages[]? // empty' "$SRC/settings.json")"

[ -n "$DEF_PROVIDER" ] || DEF_PROVIDER="deepseek"
[ -n "$DEF_MODEL" ]    || DEF_MODEL="deepseek-flash"

SETTINGS_JSON="$(jq -n --arg p "$DEF_PROVIDER" --arg m "$DEF_MODEL" --arg t "$THINKING" \
  --arg th "$THEME" --argjson pk "$PKGS_JSON" \
  '{ defaultProvider: $p, defaultModel: $m, defaultThinkingLevel: $t, theme: $th, packages: $pk }')"
SETTINGS_B64="$(printf '%s' "$SETTINGS_JSON" | base64 -w0)"

# ---- stage the recipe (what makes this agent *it*) -----------------------------
WORK="$(mktemp -d)"
STAGE="$WORK/root"
mkdir -p "$STAGE/.pi"
trap 'rm -rf "$WORK"' EXIT

for f in AGENTS.md APPEND_SYSTEM.md .gitignore web-search.json; do
  [ -e "$SRC/$f" ] && cp -a "$SRC/$f" "$STAGE/"
done
for d in prompts documented_lessons session-summarizer; do
  [ -d "$SRC/$d" ] && cp -a "$SRC/$d" "$STAGE/"
done
[ -d "$SRC/.pi/extensions" ] && cp -a "$SRC/.pi/extensions" "$STAGE/.pi/"

# strip state / logs / backups / anything secret — NEVER ship these
rm -f "$STAGE/session-summarizer/summarizer-state.json" "$STAGE/session-summarizer/summarizer.log"
find "$STAGE" -type f \( -name '*.log' -o -name '*.old' -o -name '*.jsonl' -o -name '*-state.json' \) -delete
rm -f "$STAGE/auth.json" "$STAGE/models-store.json" "$STAGE/.env"

# ---- path substitution: agent dir first, then home ------------------------------
# @@AGENT_DIR@@ -> target install dir; @@PI_HOME@@ -> target $HOME
find "$STAGE" -type f \
  \( -name '*.md' -o -name '*.json' -o -name '*.ts' -o -name '*.mjs' \
     -o -name '*.js' -o -name '*.txt' -o -name '*.sh' \) -print0 \
  | while IFS= read -r -d '' f; do
      sed -i "s|$SRC|@@AGENT_DIR@@|g; s|$HOME|@@PI_HOME@@|g" "$f"
    done

# ---- secret scan (fail loud rather than leak) -----------------------------------
if grep -RIEn '(sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|AIza[0-9A-Za-z_-]{20,}|-----BEGIN .*PRIVATE KEY-----)' "$STAGE" >/dev/null 2>&1; then
  echo "ERROR: possible secret pattern found in staged recipe files — aborting." >&2
  grep -RIEn '(sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|AIza[0-9A-Za-z_-]{20,}|-----BEGIN .*PRIVATE KEY-----)' "$STAGE" >&2 || true
  exit 1
fi

# ---- build the self-contained payload ------------------------------------------
TARBALL="$WORK/recipe.tar.gz"
tar -C "$STAGE" -czf "$TARBALL" .
PAYLOAD="$(base64 -w0 "$TARBALL")"

# ---- emit the installer ---------------------------------------------------------
OUTDIR="$HOME/.pi/agent/partner-agents/exports/$NAME"
mkdir -p "$OUTDIR"
OUT="$OUTDIR/install-$NAME.sh"

{
  # header: interpolate only the data values (single-quoted = safe for JSON/base64)
  printf '#!/usr/bin/env bash\nset -euo pipefail\n'
  printf '# Generated by export-partner-agent.sh | source: %s | %s\n\n' "$SRC" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  printf "NAME='%s'\n" "$NAME"
  printf "DEF_MODEL='%s'\n" "$DEF_MODEL"
  printf "PKGS='%s'\n" "$PKGS_LIST"
  printf "SETTINGS_B64='%s'\n" "$SETTINGS_B64"
  printf "PAYLOAD='%s'\n" "$PAYLOAD"

  # body: fully literal (quoted heredoc — all $ expand when the installer runs)
  cat <<'EOF'

AGENT_HOME="$HOME/.pi/agent"
TARGET="$HOME/.pi/partner-agents/$NAME"

echo "==> Installing partner agent '$NAME' -> $TARGET"
mkdir -p "$TARGET"
echo "$PAYLOAD" | base64 -d | tar xz -C "$TARGET"

echo "==> Resolving embedded paths"
find "$TARGET" -type f \
  \( -name '*.md' -o -name '*.json' -o -name '*.ts' -o -name '*.mjs' \
     -o -name '*.js' -o -name '*.txt' -o -name '*.sh' \) -print0 \
  | while IFS= read -r -d '' f; do
      sed -i "s|@@AGENT_DIR@@|$TARGET|g; s|@@PI_HOME@@|$HOME|g" "$f"
    done

echo "==> Linking shared credentials (target's own keys)"
ln -sfn "$AGENT_HOME/auth.json" "$TARGET/auth.json"
ln -sfn "$AGENT_HOME/models-store.json" "$TARGET/models-store.json"

echo "==> Writing trust.json + settings.json"
printf '{\n  "%s/.pi": true\n}\n' "$HOME" > "$TARGET/trust.json"
printf '%s' "$SETTINGS_B64" | base64 -d > "$TARGET/settings.json"

echo "==> Installing packages: ${PKGS:-<none>}"
for p in $PKGS; do
  [ -n "$p" ] && PI_CODING_AGENT_DIR="$TARGET" pi install "$p"
done
printf '%s' "$SETTINGS_B64" | base64 -d > "$TARGET/settings.json"

echo "==> Registering in partner-agents registry"
REG="$HOME/.pi/agent/partner-agents/partner-agents.list"
mkdir -p "$(dirname "$REG")"
[ -f "$REG" ] || : > "$REG"
grep -qxF "$TARGET" "$REG" || echo "$TARGET" >> "$REG"

echo "==> Adding pi-$NAME alias to ~/.bashrc"
if ! grep -q "pi-$NAME()" "$HOME/.bashrc" 2>/dev/null; then
  cat >> "$HOME/.bashrc" <<ALIAS
pi-$NAME() {
    set -a; source ~/.pi/agent/.env; set +a
    PI_CODING_AGENT_DIR=~/.pi/partner-agents/$NAME command pi "\$@"
}
ALIAS
fi

echo "==> Smoke test"
if [ "${SKIP_SMOKE:-0}" = "1" ]; then
  echo "    (skipped via SKIP_SMOKE=1)"
elif PI_CODING_AGENT_DIR="$TARGET" pi --print --session "$NAME-smoke" \
     "Reply with one line: your agent name and your role."; then
  echo "    Smoke test OK"
else
  echo "    Smoke test returned non-zero (check output above — install itself is complete)."
fi

echo
echo "Done. Agent '$NAME' installed at $TARGET"
echo "  - talk to it:  pi-$NAME     (after: source ~/.bashrc)"
echo "  - or:          PI_CODING_AGENT_DIR=$TARGET pi --print --session <handle> \"...\""
echo "  - model: $DEF_MODEL | packages: ${PKGS:-<none>}"
EOF
} > "$OUT"

chmod +x "$OUT"
bash -n "$OUT" && echo "    installer syntax OK" || { echo "ERROR: generated installer failed bash -n" >&2; exit 1; }

echo
echo "Exported: $OUT ($(du -h "$OUT" | cut -f1))"
echo "Settings: provider=$DEF_PROVIDER model=$DEF_MODEL thinking=${THINKING:-<unset>} theme=${THEME:-<unset>} packages=${PKGS_LIST:-<none>}"
echo
echo "Recipe manifest (files that ship):"
( cd "$STAGE" && find . -type f | sort )
